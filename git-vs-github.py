# GIT : git is like a save system for your code.It tracks every change you make , lets you go back to previous versions 
# and lets you collaborate with other members of your team

# GIT Hub : git hub is a place , where you store your git projects online - you can think of it as google drive for your code.

# how git works
# 1. you write code : make changes to your file
# 2. you save a snapshot : called "commit" in git
# 3. git remembers snapshot : who made it , when and why


# Key concepts  
# 1. repository : a project tracked by git
# ex.:= git init krne pr bnta h git repo

# 2. staging : choosing which changes to save
# ex.:= selecting items before putting them in box for shipping

# 3. commit : saved snapshot of your code
# ex.:= like saving in a video game you can always go back

# 4. push : upload your commits to git hub
# backs up your code online

# 5. pull : download chnages from git hub
#  get updates when working with others

# 6. clone : copy a project from git hub

